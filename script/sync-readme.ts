import {readFile, writeFile} from "node:fs/promises";

/*
 * 루트 README와 사이트 홈 동기화. 본문 유지, 문서와 이미지 경로만 사이트 기준으로 변환
 */
const source = await readFile(new URL("../README.md", import.meta.url), "utf8");

await writeFile(
	new URL("../content/README.md", import.meta.url),
	`<!-- Generated by npm run sync:readme from README.md. -->\n\n${source
		.replaceAll('src="content/asset/', 'src="asset/')
		.replaceAll("](content/public/", "](public/")
		.replaceAll("](AGENTS.template.md)", "](https://github.com/nomeehej/agent-conventions/blob/main/AGENTS.template.md)")
		.replaceAll("](CONTRIBUTING.md)", "](https://github.com/nomeehej/agent-conventions/blob/main/CONTRIBUTING.md)")
		.replaceAll("](LICENSE)", "](https://github.com/nomeehej/agent-conventions/blob/main/LICENSE)")
		.replace(
			/\]\(https:\/\/nomeehej\.github\.io\/agent-conventions\/convention\/(react|typescript|css|testing|figma)\/\)/g,
			"](public/convention/$1.md)",
		)}`,
);
